"""Embeds Evince's own rendering widget (EvView) for native PDF display,
text selection, and highlight-annotation anchors.

Anchors are real EvAnnotation (AnnotationTextMarkup / highlight) objects —
Evince's own renderer draws them, so there is no custom overlay-drawing
code. A click on a highlight is hit-tested against the document's
annotation mapping and reported via `on_anchor_clicked`.

Image-region anchors (Ctrl+drag a rectangle on the page; see README) reuse
the anchor storage layout but render as a faint blue rectangle on a
Gtk.DrawingArea overlaid on top of EvView — Evince's annotation model is
text-only, so a non-text region can't become a real annotation. The
captured PNG is generated by rendering the page through the Evince
backend (`Document.render` → cairo surface → pixbuf → subpixbuf crop →
PNG bytes) so it's independent of what's currently visible on screen.
"""
from __future__ import annotations

import gi
import weakref

gi.require_version("Gtk", "3.0")
gi.require_version("EvinceDocument", "3.0")
gi.require_version("EvinceView", "3.0")
from gi.repository import (  # noqa: E402
    EvinceDocument,
    EvinceView,
    Gdk,
    GdkPixbuf,
    Gio,
    GLib,
    Gtk,
)

EvinceDocument.init()

HIGHLIGHT_RGBA = Gdk.RGBA(1.0, 0.85, 0.2, 0.35)  # translucent yellow, like a real highlighter
SEARCH_HIT_RGBA = Gdk.RGBA(1.0, 0.5, 0.0, 0.35)  # translucent orange, distinct from anchor yellow
# Faint blue, deliberately distinct from anchor yellow and search orange so a
# Ctrl+drag region is visually identifiable as a different kind of mark.
REGION_RGBA_FILL = Gdk.RGBA(0.20, 0.45, 0.95, 0.16)
REGION_RGBA_STROKE = Gdk.RGBA(0.15, 0.35, 0.85, 0.70)
# While the user is actively dragging, the same colors but darker and
# fully opaque so the rubber band reads as a "live" selection.
RUBBERBAND_FILL = Gdk.RGBA(0.20, 0.45, 0.95, 0.20)
RUBBERBAND_STROKE = Gdk.RGBA(0.10, 0.25, 0.70, 1.0)

# Render the captured page region at this scale (PDF points × scale = pixels).
# 2.0 = 144 DPI, which is enough for vision LLMs to read small text without
# ballooning memory for full-page screenshots.
REGION_CAPTURE_SCALE = 2.0
# Minimum rubber-band size in PDF points before we treat it as a real region.
# Anything smaller is almost certainly an accidental click, not an intent
# to ask about something.
MIN_REGION_PTS = 4.0


class ReaderView(Gtk.ScrolledWindow):
    def __init__(self):
        super().__init__()
        self.model = EvinceView.DocumentModel.new()
        self.view = EvinceView.View.new()
        self.view.set_model(self.model)

        # EvView's GTK parent *must* be a GtkScrolledWindow — its C
        # constructor asserts it (ev_view_parent_set in libview/ev-view.c:
        # `!parent || GTK_IS_SCROLLED_WINDOW (parent)`). An earlier draft
        # wrapped `self.view` in a Gtk.Overlay here so a sibling
        # DrawingArea could paint region rectangles on top, but the
        # assertion aborted the whole app on launch with `Bail out!`.
        # So: EvView stays a direct child of this ScrolledWindow, and
        # we paint region rectangles inside its OWN draw callback after
        # EvView has rendered the page. Functionally equivalent — the
        # cairo context handed to `draw` covers exactly the same
        # viewport area a sibling overlay would have — and we avoid
        # fighting EvView's parent requirement.
        self.add(self.view)

        self.document = None
        self.path = None

        self.on_selection_changed = None   # callback(text: str)
        self.on_anchor_created = None       # callback(page_index: int, rect: dict)
        self.on_anchor_clicked = None       # callback(annot)
        self.on_page_changed = None         # callback(page_index: int)
        self.on_copy = None                 # callback(text: str) — fired after a successful copy
        # Fires after the user finishes a Ctrl+drag region capture.
        # Callback signature: (page_index: int, rect: dict, png_bytes: bytes).
        self.on_region_created = None
        # Fires when the user clicks an existing region overlay. Callback
        # signature: (message_id: str) — the chat panel resolves that to a
        # session/message and scrolls the chat to it.
        self.on_region_clicked = None

        self._annot_index: dict[int, tuple[int, object]] = {}  # id(annot) -> (page_index, annot)
        # Weakrefs to search-hit annotations, so we don't extend their
        # lifetime beyond what the document wants. When the document is
        # replaced, its annotations are unrefed by the backend and our
        # weakrefs silently become dead — `_clear_search_hits` then
        # just drops the dead refs instead of crashing on a freed GObject.
        self._search_hits: list[tuple[int, dict, weakref.ref]] = []  # (page_index, rect, weakref)
        self._recording = False
        self._created_batch: list[tuple[int, dict, object]] = []

        # Image-region state. `_region_overlays` is the canonical list of
        # persistent rectangles to draw; `_region_by_message` is the
        # reverse lookup for click hit-tests. Both are wiped on document
        # load (see load()), matching the treatment of real annotations.
        self._region_overlays: list[tuple[int, dict, str]] = []  # (page_index, rect, message_id)
        self._region_by_message: dict[str, tuple[int, dict]] = {}  # message_id -> (page, rect)
        # Live drag state. `_region_dragging` is True between the
        # button-press that started a Ctrl+drag and the matching
        # button-release. `_region_rubber_band` is the current rect in
        # page-point space (or None); it's drawn on the overlay while
        # the drag is in progress and cleared on release.
        self._region_dragging = False
        self._region_start: tuple[float, float, int] | None = None  # (page_x, page_y, page_index)
        self._region_rubber_band: tuple[float, float, float, float] | None = None

        # Text selection + copy. EvView is a custom widget — it supports
        # drag-selecting text out of the box, but it does NOT inherit the
        # standard GtkEditable Ctrl+C/Ctrl+X shortcuts. Without an
        # explicit handler, Ctrl+C in the reader silently does nothing,
        # which is what prompted the bug report. The plumbing below makes
        # selection work for the keyboard and a right-click menu alike.
        #
        # can_focus has to be true for the view to ever receive
        # key-press-event. We also grab focus on button press — without
        # that, the chat panel's Gtk.Entry (or the toolbar's spinbutton)
        # usually owns focus after any click outside the reader, so
        # Ctrl+C routes there instead.
        self.view.set_can_focus(True)
        self.view.set_focus_on_click(True)

        self.view.connect("selection-changed", self._on_selection_changed)
        self.view.connect("annot-added", self._on_annot_added)
        self.view.connect("button-press-event", self._on_button_press)
        # button-release-event fires after a drag-select finishes; pop
        # the context menu on right-click there (button-press is too
        # early — popdown against an undisposed grab can be flaky).
        self.view.connect("button-release-event", self._on_button_release)
        self.view.connect("motion-notify-event", self._on_motion_notify)
        self.view.connect("key-press-event", self._on_key_press)
        # Ctrl+Insert is a separate handler so the same callback isn't
        # doing two unrelated keyval checks in one method — clearer to
        # read and easier to detach if a future GTK version starts
        # binding the key itself.
        self.view.connect("key-press-event", self._on_key_press_insert)
        # GTK's "draw" signal is RUN_LAST: a plain connect() fires BEFORE
        # EvView's own class-default paint, so anything drawn there gets
        # immediately painted over by the page render. connect_after()
        # runs after the default handler, which is what actually puts our
        # region rectangles (Ctrl+drag anchors) on top of the rendered
        # page. Returning False propagates to GTK's default handler so no
        # other draw consumer is starved.
        self.view.connect_after("draw", self._on_view_draw)
        self.model.connect("page-changed", self._on_page_changed)

    # ---- loading -----------------------------------------------------

    def load(self, path: str) -> None:
        uri = Gio.File.new_for_path(path).get_uri()
        document = EvinceDocument.Document.factory_get_document(uri)
        self.document = document
        self.path = path
        self._annot_index.clear()
        self._clear_search_hits()
        # Region overlays are not part of the Evince document — they live
        # in our own list — but they're keyed to the previous document's
        # page geometry, so they have to go when the document changes.
        # The chat panel re-populates them via restore_region_overlays()
        # right after open_path() calls load().
        self._region_overlays.clear()
        self._region_by_message.clear()
        self._region_dragging = False
        self._region_rubber_band = None
        self.model.set_document(document)

    @property
    def page_count(self) -> int:
        return self.document.get_n_pages() if self.document else 0

    @property
    def current_page(self) -> int:
        """0-indexed current page; -1 when no document is loaded."""
        return self.model.get_page() if self.document else -1

    @property
    def inverted_colors(self) -> bool:
        """Whether the renderer is in inverted-color mode (white-on-black
        instead of black-on-white). Implemented as a property so callers
        don't reach through to `model.set_inverted_colors` directly —
        keeping the DocumentModel an implementation detail."""
        return self.model.get_inverted_colors()

    @inverted_colors.setter
    def inverted_colors(self, enabled: bool) -> None:
        self.model.set_inverted_colors(bool(enabled))

    def _on_page_changed(self, _model, _old_page, new_page) -> None:
        if self.on_page_changed:
            self.on_page_changed(new_page)

    def page_text(self, page_index: int) -> str | None:
        if self.document is None:
            return None
        text = self.document.get_text(self.document.get_page(page_index))
        text = (text or "").strip()
        return text or None

    def go_to_page(self, page_index: int) -> None:
        self.model.set_page(page_index)

    def go_to_anchor(self, page_index: int, rect: dict) -> None:
        """Scroll to the exact anchor position on a page, not just the
        page's top. get_page_extents() returns the page's rect in
        absolute document-scroll coordinates (its y matches the vertical
        adjustment's value directly, unaffected by further scrolling), so
        the target adjustment value is that rect's top plus the anchor's
        offset into the page — no viewport-relative math needed.

        set_page() triggers its own async scroll-to-page-top that lands
        *after* an idle callback fires and overwrites a same-idle-cycle
        adjustment change — confirmed by tracing vadjustment across
        frames. So the fine-scroll is applied twice, at 60ms and 250ms:
        the first catches most cases, the second is a safety net for a
        slower layout pass on a large document."""
        self.model.set_page(page_index)

        def _fine_scroll():
            # The 60/250 ms timeouts can fire after the document has been
            # replaced or the window destroyed (e.g. when the user opens a
            # new file mid-navigation). Bail out if the document we
            # targeted is no longer the active one — `get_vadjustment()`
            # returning None is the "widget is gone" signal in GTK terms.
            if self.document is None:
                return False
            page_area = Gdk.Rectangle()
            found = self.view.get_page_extents(page_index, page_area, Gtk.Border())
            vadj = self.get_vadjustment()
            if not found or vadj is None:
                return False
            scale = self.model.get_scale()
            target = page_area.y + rect["y1"] * scale - 24  # small top margin
            upper = max(vadj.get_lower(), vadj.get_upper() - vadj.get_page_size())
            vadj.set_value(min(max(target, vadj.get_lower()), upper))
            return False

        GLib.timeout_add(60, _fine_scroll)
        GLib.timeout_add(250, _fine_scroll)

    # ---- selection / anchors -----------------------------------------

    def selected_text(self) -> str | None:
        text = self.view.get_selected_text()
        return text.strip() if text else None

    def _on_selection_changed(self, _view) -> None:
        if self.on_selection_changed:
            self.on_selection_changed(self.selected_text())

    def create_anchor_from_selection(self):
        """Turn the current text selection into highlight annotation(s).
        Usually one, but a selection dragged across a page boundary fires
        'annot-added' once per page — all of them are returned so callers
        can track/clean up every highlight the selection produced, even
        though only the first is treated as the anchor's canonical
        (page, rect) for persistence. Returns a list, empty if there was
        no active selection."""
        text = self.selected_text()
        if not text:
            return []
        self._recording = True
        self._created_batch = []
        self.view.add_text_markup_annotation_for_selected_text()
        self._recording = False
        return self._created_batch

    def _on_annot_added(self, _view, annot) -> None:
        page_index = annot.get_page_index()
        area = annot.get_area()
        annot.set_rgba(HIGHLIGHT_RGBA)
        self._annot_index[id(annot)] = (page_index, annot)
        rect = {"x1": area.x1, "y1": area.y1, "x2": area.x2, "y2": area.y2}
        if self._recording:
            self._created_batch.append((page_index, rect, annot))
        if self.on_anchor_created:
            self.on_anchor_created(page_index, rect, annot)

    def restore_anchor(self, page_index: int, rect: dict, contents: str = ""):
        """Recreate a highlight annotation from a persisted anchor (on
        document reopen). Does not fire on_anchor_created. Returns annot."""
        if self.document is None:
            return None
        page = self.document.get_page(page_index)
        annot = EvinceDocument.AnnotationTextMarkup.highlight_new(page)
        area = EvinceDocument.Rectangle()
        area.x1, area.y1, area.x2, area.y2 = rect["x1"], rect["y1"], rect["x2"], rect["y2"]
        annot.set_area(area)
        annot.set_contents(contents)
        annot.set_rgba(HIGHLIGHT_RGBA)
        out_rect = EvinceDocument.Rectangle()
        self.document.add_annotation(annot, out_rect)
        self._annot_index[id(annot)] = (page_index, annot)
        return annot

    def remove_annotation(self, annot) -> None:
        """Remove a highlight annotation (e.g. its anchor was deleted)."""
        if annot is None:
            return
        self.view.remove_annotation(annot)
        self._annot_index.pop(id(annot), None)

    # ---- search ------------------------------------------------------

    def find_text_all(self, query: str, case_sensitive: bool = False,
                      cancel_flag: list[bool] | None = None,
                      progress: callable = None) -> list[tuple[int, dict]]:
        """Search every page of the loaded document for `query`.

        Returns a flat list of (page_index, rect_dict) tuples in document
        order. The Evince backend only finds within a single page per call,
        so we iterate; `progress(n_pages_done, n_pages_total)` is called
        after each page so callers can drive a progress indicator. If
        `cancel_flag` is a one-element list whose first item becomes True,
        the search stops early and returns what was found so far."""
        results: list[tuple[int, dict]] = []
        if self.document is None or not query:
            return results
        n_pages = self.document.get_n_pages()
        for i in range(n_pages):
            if cancel_flag and cancel_flag[0]:
                break
            page = self.document.get_page(i)
            try:
                rects = self.document.find_text(page, query, case_sensitive)
            except Exception:
                rects = []
            for r in rects or []:
                results.append((i, {"x1": r.x1, "y1": r.y1, "x2": r.x2, "y2": r.y2}))
            if progress:
                progress(i + 1, n_pages)
        return results

    def _clear_search_hits(self) -> None:
        """Remove every visible search-hit annotation. Called when a new
        search starts or the document is reloaded.

        Each entry is a weakref — the document owns the annotation and
        unrefs it when the doc is replaced, so a weakref may already be
        dead by the time we get here. We drop dead refs outright
        (without touching them) and remove still-live ones through the
        view. This avoids the GLib "G_IS_OBJECT (object)" assertion
        crashes that show up if we try to call view.remove_annotation on
        an already-freed object."""
        kept = []
        for page_index, rect, ref in self._search_hits:
            annot = ref()
            if annot is None:
                continue
            kept.append((page_index, rect, ref))
            try:
                self.view.remove_annotation(annot)
            except Exception:
                kept.pop()
        self._search_hits = kept

    def highlight_search_match(self, page_index: int, rect: dict) -> None:
        """Drop a transient orange highlight annotation on the current
        match. Earlier search-hit annotations stay visible too — the user
        sees orange overlays for every page that has matches, with the
        current match visually identical to the others (we use a single
        color rather than varying it, since varying colors per hit would
        only make this easier to confuse with anchor highlights)."""
        if self.document is None:
            return
        page = self.document.get_page(page_index)
        annot = EvinceDocument.AnnotationTextMarkup.highlight_new(page)
        area = EvinceDocument.Rectangle()
        area.x1, area.y1, area.x2, area.y2 = rect["x1"], rect["y1"], rect["x2"], rect["y2"]
        annot.set_area(area)
        annot.set_rgba(SEARCH_HIT_RGBA)
        out_rect = EvinceDocument.Rectangle()
        self.document.add_annotation(annot, out_rect)
        # Weakref: the document owns `annot` and unrefs it on doc
        # replacement, so we can't safely hold a strong ref here. The
        # weakref dies silently when the doc frees the annotation, and
        # `_clear_search_hits` skips dead entries instead of dereferencing
        # freed GObjects (which would trigger G_IS_OBJECT assertion crashes).
        self._search_hits.append((page_index, rect, weakref.ref(annot)))

    def clear_search_highlights(self) -> None:
        """Clear all visible search-hit highlights (e.g. when the search
        bar closes)."""
        self._clear_search_hits()

    def _on_button_press(self, _widget, event):
        """Hit-test against our own tracked annotations, not EvMappingList
        (its `.data` comes back as a raw gpointer int through GI — not
        usable as a Python object — so identity has to come from the
        Annotation instances we already hold from creation/restore).

        get_page_extents() returns page rects in absolute document-scroll
        coordinates, but GdkEventButton.x/y are viewport-relative — they
        only coincide when the vertical adjustment is 0 (page 0, unscrolled).
        Convert the event into the same absolute space before comparing.

        Ctrl+button-1 takes a different branch entirely: it starts an
        image-region drag (see _on_motion_notify / _on_button_release).
        We consume the event by returning True so EvView's own
        drag-select-text logic never engages — without this, Ctrl+drag
        would BOTH start a text selection AND a region drag, and the
        final selection would race the region capture for the click."""
        # Grab focus on every click so subsequent key events (Ctrl+C etc.)
        # route to the reader view rather than the chat composer or toolbar
        # widget that happened to own focus before.
        self.view.grab_focus()
        if event.button != 1 or self.document is None:
            return False
        # Ctrl+button-1 → start an image-region drag. We only check the
        # modifier state at button-press time; if the user releases Ctrl
        # mid-drag, the drag still completes (matches every other
        # Ctrl+drag UX in GTK apps). Without a drag, a bare Ctrl+click is
        # a no-op rather than a 0×0 capture, which keeps "Ctrl+click on
        # a sentence to deselect" working on Mac-style keyboards too.
        state = event.get_state()
        if state & Gdk.ModifierType.CONTROL_MASK:
            return self._begin_region_drag(event)
        current = self.model.get_page()
        scale = self.model.get_scale()
        vadj = self.get_vadjustment()
        hadj = self.get_hadjustment()
        abs_x = event.x + (hadj.get_value() if hadj else 0)
        abs_y = event.y + (vadj.get_value() if vadj else 0)
        for page_index in range(max(0, current - 2), min(self.page_count, current + 3)):
            rect = Gdk.Rectangle()
            found = self.view.get_page_extents(page_index, rect, Gtk.Border())
            if not found:
                continue
            if not (rect.x <= abs_x <= rect.x + rect.width
                    and rect.y <= abs_y <= rect.y + rect.height):
                continue
            doc_x = (abs_x - rect.x) / scale
            doc_y = (abs_y - rect.y) / scale
            # Region-overlay hit-test first: image-region overlays take
            # precedence over highlight annotations on the same page,
            # since they're drawn on top. If we ever had both at the
            # same screen pixel, the visible mark on top is the region.
            for region_page, region_rect, message_id in self._region_overlays:
                if region_page != page_index:
                    continue
                if (region_rect["x1"] <= doc_x <= region_rect["x2"]
                        and region_rect["y1"] <= doc_y <= region_rect["y2"]):
                    if self.on_region_clicked:
                        self.on_region_clicked(message_id)
                    return True
            for annot_page, annot in self._annot_index.values():
                if annot_page != page_index:
                    continue
                a = annot.get_area()
                if a.x1 <= doc_x <= a.x2 and a.y1 <= doc_y <= a.y2:
                    if self.on_anchor_clicked:
                        self.on_anchor_clicked(annot)
                    return True
        return False

    # ---- selection / copy --------------------------------------------

    def copy_selection(self) -> bool:
        """Copy the currently-selected PDF text to the system clipboard.

        Writes to BOTH the default clipboard (Ctrl+V) and the primary
        selection (middle-click paste, X11's secondary mechanism) — many
        Linux users expect middle-click to work after highlighting, and
        only setting the default clip leaves that broken. Returns True
        when something was copied, False when there was no selection to
        copy (callers can use that to e.g. flash a status message)."""
        text = self.selected_text()
        if not text:
            return False
        clipboard = Gtk.Clipboard.get_default(Gdk.Display.get_default())
        clipboard.set_text(text, -1)
        # Also set the X11 primary selection — on Wayland this is a no-op
        # via Gtk.Clipboard; on X11 it makes middle-click paste work.
        try:
            primary = Gtk.Clipboard.get(Gdk.SELECTION_PRIMARY)
            primary.set_text(text, -1)
        except Exception:
            # Some Wayland sessions don't expose SELECTION_PRIMARY; the
            # default clipboard already got the text, so this is best-effort.
            pass
        if self.on_copy:
            self.on_copy(text)
        return True

    def _on_key_press(self, _widget, event):
        """Handle Ctrl+C / Ctrl+Insert / Cmd+C → copy the current
        selection to the clipboard.

        EvView doesn't bind these by default, so without this handler a
        user who highlights text and hits Ctrl+C gets nothing — the
        default behavior for unwired keys is just to swallow the event.
        We deliberately also accept Ctrl+Insert (the X11 convention
        when Ctrl+C is in use by the terminal/window manager) and
        Super+C is intentionally NOT bound, since that's typically the
        WM's own shortcut on GNOME.
        """
        # Gdk.KEY_c (lowercase, no Shift) — Ctrl+C and Cmd+C both come
        # through here because PRIMARY_MOD_MASK includes both ControlMask
        # and Mod2Mask/SuperMask handling for the meta key in a unified
        # bitfield on most platforms; checking ControlMask | Mod4Mask
        # covers Ctrl and Super (Cmd on Mac-style keyboards).
        if event.keyval != Gdk.KEY_c:
            return False
        state = event.get_state()
        ctrl_or_cmd = bool(state & (Gdk.ModifierType.CONTROL_MASK | Gdk.ModifierType.META_MASK))
        # Ignore if Shift/Alt/Hyper are also held — that lets the user
        # still chain Ctrl+Shift+C, Alt+C, etc. without us intercepting.
        noisy = state & (
            Gdk.ModifierType.SHIFT_MASK
            | Gdk.ModifierType.MOD1_MASK
            | Gdk.ModifierType.MOD2_MASK
            | Gdk.ModifierType.MOD4_MASK
            | Gdk.ModifierType.HYPER_MASK
        )
        # But we DO want Cmd+C (META_MASK only, no Shift/Alt) — strip the
        # cmd bit from "noisy" so it counts as a plain copy on macOS-style
        # keyboards. On Linux Ctrl+C is the common path; META-only is rare
        # but harmless to allow here.
        if ctrl_or_cmd:
            noisy &= ~Gdk.ModifierType.META_MASK
            if not noisy:
                return self.copy_selection() is not False
        return False

    def _on_key_press_insert(self, _widget, event):
        """Ctrl+Insert → copy. Bound separately so a user who can't reach
        Ctrl+C (e.g. tmux/screen grabbing it) still has a working key."""
        if event.keyval != Gdk.KEY_Insert:
            return False
        state = event.get_state()
        if state & Gdk.ModifierType.CONTROL_MASK:
            return self.copy_selection() is not False
        return False

    def _on_button_release(self, _widget, event):
        """Right-click → show the context menu with a Copy entry. We do
        this on release (not press) because EvView's own selection-drag
        logic consumes the press; doing it on release also matches the
        GTK HIG for right-click popups.

        Left-button release also finalizes an in-progress Ctrl+drag
        image-region capture. We always run that branch first (before
        any menu logic) so a stray right-click never accidentally
        captures a region — and so a bare Ctrl+click with no drag
        clears the rubber band and is otherwise a no-op."""
        if self._region_dragging and event.button == 1:
            self._finalize_region_drag(event)
            return True
        if event.button != 3 or self.document is None:
            return False
        if not self.selected_text():
            # No selection — no point in showing a Copy-only menu.
            return False
        menu = Gtk.Menu()
        copy_item = Gtk.MenuItem(label="Copy")
        copy_item.connect("activate", lambda _i: self.copy_selection())
        menu.append(copy_item)
        menu.show_all()
        menu.popup_at_pointer(event)
        return True

    # ---- image-region capture (Ctrl+drag) ----------------------------

    def _event_to_page_point(self, event):
        """Convert a viewport-relative event (button/motion) into the
        page point + page index it's over. Returns (page_index, page_x,
        page_y) or None if the event is over the gutter between pages /
        outside any visible page.

        Used by both the drag-start (where it doubles as a guard that
        the press happened on a page, not the toolbar background) and
        every motion update (to clamp the cursor to the current page's
        bounds). Identical math to the one in _on_button_press, factored
        out so the region code doesn't have to reach through GTK's
        adjustments on its own."""
        vadj = self.get_vadjustment()
        hadj = self.get_hadjustment()
        abs_x = event.x + (hadj.get_value() if hadj else 0)
        abs_y = event.y + (vadj.get_value() if vadj else 0)
        scale = self.model.get_scale()
        # The region drag only ever belongs to the currently visible
        # page; we don't support dragging across a page boundary mid-
        # capture. Evince itself exposes get_page_extents for any page,
        # but a cross-page capture is hard to reason about (the rect
        # would have to be expressed across two coordinate systems) and
        # not requested, so we anchor on the model-reported current page.
        page_index = self.model.get_page()
        if page_index < 0 or page_index >= self.page_count:
            return None
        rect = Gdk.Rectangle()
        if not self.view.get_page_extents(page_index, rect, Gtk.Border()):
            return None
        if not (rect.x <= abs_x <= rect.x + rect.width
                and rect.y <= abs_y <= rect.y + rect.height):
            return None
        page_x = (abs_x - rect.x) / scale
        page_y = (abs_y - rect.y) / scale
        return page_index, page_x, page_y

    def _begin_region_drag(self, event) -> bool:
        """Start a Ctrl+drag image-region capture. Records the press
        location in page-point space and arms the rubber band. Returns
        True so the original button-press is consumed — EvView's text-
        selection drag never engages."""
        located = self._event_to_page_point(event)
        if located is None:
            # Press landed outside any page (e.g. the gutter between
            # pages in a dual-page layout). Treat as a no-op rather
            # than silently starting a region that can't be captured.
            return True
        page_index, page_x, page_y = located
        self._region_dragging = True
        self._region_start = (page_x, page_y, page_index)
        self._region_rubber_band = (page_x, page_y, 0.0, 0.0)
        self.view.queue_draw()
        return True

    def _on_motion_notify(self, _widget, event):
        """Update the rubber-band rect while a region drag is in
        progress. Only fires for button-1 motion (GTK's BUTTON1_MOTION
        mask is auto-enabled with BUTTON_PRESS); no need to filter
        button state here. Returns True so EvView's own drag-text
        handler — which would otherwise try to start a text selection
        on the same gesture — never sees the event."""
        if not self._region_dragging or self._region_start is None:
            return False
        located = self._event_to_page_point(event)
        if located is None:
            # Cursor wandered off the page; keep the drag alive but
            # freeze the rubber band at its last in-bounds extent. The
            # release handler will then capture whatever shape we've
            # actually drawn — typically nothing if the cursor never
            # came back on-page, and that's the right outcome.
            return True
        page_index, page_x, page_y = located
        start_x, start_y, start_page = self._region_start
        if page_index != start_page:
            # Same comment as above for cross-page motion. Clamp the
            # cursor to the original page's bounds before computing
            # the rect, so the rubber band stays on one page.
            rect = Gdk.Rectangle()
            if not self.view.get_page_extents(start_page, rect, Gtk.Border()):
                return True
            scale = self.model.get_scale()
            page_w = rect.width / scale
            page_h = rect.height / scale
            page_x = max(0.0, min(page_x, page_w))
            page_y = max(0.0, min(page_y, page_h))
        x1 = min(start_x, page_x)
        y1 = min(start_y, page_y)
        x2 = max(start_x, page_x)
        y2 = max(start_y, page_y)
        self._region_rubber_band = (x1, y1, x2 - x1, y2 - y1)
        self.view.queue_draw()
        return True

    def _finalize_region_drag(self, event) -> None:
        """Capture the page region the user just dragged. Renders the
        page through the Evince backend, crops to the rect, encodes as
        PNG, fires `on_region_created` so the chat panel can attach
        the image to the next message, and (since the rect is now
        "anchored") queues a redraw to drop the rubber band and pick up
        the persistent overlay styling.

        If the rect is below MIN_REGION_PTS in either dimension the
        drag is treated as a stray click — we clear the rubber band
        and do nothing. This also handles the Ctrl+click-without-drag
        case (the user wanted to deselect or focus the view, not
        capture a region)."""
        self._region_dragging = False
        band = self._region_rubber_band
        self._region_rubber_band = None
        self._region_start = None
        if band is None:
            self.view.queue_draw()
            return
        x1, y1, w, h = band
        # Normalize: drag from bottom-right to top-left gives us a
        # negative w/h, which is fine for storage but easier to debug
        # if we flip them. _on_motion_notify already enforces min/max,
        # so this is just defensive.
        if w < 0:
            x1, w = x1 + w, -w
        if h < 0:
            y1, h = y1 + h, -h
        if w < MIN_REGION_PTS or h < MIN_REGION_PTS:
            self.view.queue_draw()
            return
        page_index = self.model.get_page() if self.document else -1
        if page_index < 0:
            self.view.queue_draw()
            return
        rect = {"x1": x1, "y1": y1, "x2": x1 + w, "y2": y1 + h}
        png_bytes = self.capture_page_region(page_index, rect)
        if png_bytes is None:
            # Capture failed (no document, page out of range, render
            # error). Surface this to the chat panel as a no-bytes
            # callback so it can show a status message — silently
            # swallowing would make the user wonder why their Ctrl+drag
            # did nothing.
            if self.on_region_created:
                self.on_region_created(page_index, rect, None)
            self.view.queue_draw()
            return
        # The chat panel owns the message_id and will call back into
        # add_region_overlay() once the message is saved. We don't add
        # the overlay here — at this point there's no message to
        # associate it with, and adding it would risk creating an
        # orphan overlay if the user backs out of sending.
        if self.on_region_created:
            self.on_region_created(page_index, rect, png_bytes)
        self.view.queue_draw()

    def capture_page_region(self, page_index: int, rect: dict) -> bytes | None:
        """Render the loaded document's page through Evince's own
        backend, crop to `rect` (page-point coords), and return the
        result as PNG bytes. Returns None if any step fails.

        Why render through the document instead of screenshotting the
        widget? Two reasons: (1) it captures at a chosen scale,
        independent of the on-screen zoom — a 100%-zoomed-out reader
        shouldn't ship a postage-stamp image to the LLM; (2) it works
        even when the selected rect is currently scrolled off-screen,
        because the rendering is from the document model, not the
        visible viewport. The rendered surface is in top-left origin
        page-point coordinates, which is also the rect's coordinate
        system, so the subpixbuf crop is just (x1, y1, w, h).

        Renders at REGION_CAPTURE_SCALE (2.0 = 144 DPI) — enough
        resolution for vision LLMs to read small text without bloating
        memory for accidental full-page captures."""
        if self.document is None:
            return None
        if page_index < 0 or page_index >= self.document.get_n_pages():
            return None
        try:
            page = self.document.get_page(page_index)
            # Evince's `Document.render` takes a single EvRenderContext,
            # not (page, rotation, scale) directly — the context bundles
            # those three. Rotation is in 90° units (0/90/180/270); we
            # always render at rotation 0 since image rotations are
            # uncommon in the typical reading flow, and the rect is
            # stored in the un-rotated coordinate system anyway.
            rc = EvinceDocument.RenderContext.new(page, 0, REGION_CAPTURE_SCALE)
            surface = self.document.render(rc)
            pixbuf = Gdk.pixbuf_get_from_surface(
                surface, 0, 0, surface.get_width(), surface.get_height()
            )
        except Exception:
            # `render` can fail on a few backends (e.g. password-
            # protected PDFs without the password supplied). Returning
            # None lets the caller surface a clear error to the user
            # rather than a half-broken image.
            return None
        if pixbuf is None:
            return None
        # Clamp the rect to the rendered surface bounds. A user who
        # drags a tiny bit past the page edge should still get a clean
        # crop, not a GdkPixbuf "subpixbuf out of range" critical.
        scale = REGION_CAPTURE_SCALE
        page_w = pixbuf.get_width()
        page_h = pixbuf.get_height()
        x1 = max(0, min(int(round(rect["x1"] * scale)), page_w))
        y1 = max(0, min(int(round(rect["y1"] * scale)), page_h))
        x2 = max(0, min(int(round(rect["x2"] * scale)), page_w))
        y2 = max(0, min(int(round(rect["y2"] * scale)), page_h))
        w = x2 - x1
        h = y2 - y1
        if w < 4 or h < 4:
            return None
        try:
            cropped = GdkPixbuf.Pixbuf.new_subpixbuf(pixbuf, x1, y1, w, h)
            ok, buf = cropped.save_to_bufferv("png", [], [])
        except Exception:
            return None
        if not ok or not buf:
            return None
        return bytes(buf)

    def add_region_overlay(self, page_index: int, rect: dict, message_id: str) -> None:
        """Persist a region overlay for `message_id` so it stays
        visible after the message is sent and across document reopens.
        Called by the chat panel once it has saved the message row.

        Inserting at the head (rather than appending) means newer
        regions draw on top of older ones — matches typical
        "last-drawn-wins" expectations and means an active rubber band
        for the same page, if one ever exists, would be visible over
        older overlays. The chat panel never relies on order, so this
        is purely cosmetic."""
        self._region_overlays.insert(0, (page_index, dict(rect), message_id))
        self._region_by_message[message_id] = (page_index, dict(rect))
        self.view.queue_draw()

    def remove_region_overlay(self, message_id: str) -> None:
        """Drop the overlay whose anchor message was deleted."""
        if message_id not in self._region_by_message:
            return
        del self._region_by_message[message_id]
        self._region_overlays = [
            entry for entry in self._region_overlays
            if entry[2] != message_id
        ]
        self.view.queue_draw()

    def clear_region_overlays(self) -> None:
        """Wipe every region overlay (e.g. before restoring from DB on
        a document reopen). Distinct from `remove_region_overlay`
        which drops a single one."""
        self._region_overlays.clear()
        self._region_by_message.clear()
        self.view.queue_draw()

    def _on_view_draw(self, _widget, cr):
        """Draw both the live rubber band (if a Ctrl+drag is in
        progress) and every persistent region overlay. The cairo
        context GTK hands us here is the same one EvView just used to
        paint the page — same coordinate system, same viewport
        translation. `get_page_extents()` returns page rects in
        absolute document-scroll coordinates; subtracting the
        ScrolledWindow's adjustment values lands them in viewport
        space, which is what the cairo context here expects.

        Returns False (don't swallow the signal) so GTK keeps painting
        anything else on top. Drawing order: rubber band last so it's
        always visible during a drag, even if it overlaps a stored
        region."""
        if (not self._region_overlays
                and self._region_rubber_band is None
                and not self._region_dragging):
            return False
        vadj = self.get_vadjustment()
        hadj = self.get_hadjustment()
        vx = hadj.get_value() if hadj else 0
        vy = vadj.get_value() if vadj else 0
        scale = self.model.get_scale()
        # Helper inline — drawing code is small enough that splitting
        # it out would make the math harder to follow.
        def draw_rect(x1, y1, x2, y2, fill, stroke, line_w=1.5):
            w = max(0.0, x2 - x1)
            h = max(0.0, y2 - y1)
            cr.rectangle(x1, y1, w, h)
            cr.set_source_rgba(fill.red, fill.green, fill.blue, fill.alpha)
            cr.fill_preserve()
            cr.set_source_rgba(stroke.red, stroke.green, stroke.blue, stroke.alpha)
            cr.set_line_width(line_w)
            cr.stroke()
        # Persistent overlays first.
        for page_index, rect, _msg_id in self._region_overlays:
            page_area = Gdk.Rectangle()
            if not self.view.get_page_extents(page_index, page_area, Gtk.Border()):
                continue
            draw_rect(
                page_area.x + rect["x1"] * scale - vx,
                page_area.y + rect["y1"] * scale - vy,
                page_area.x + rect["x2"] * scale - vx,
                page_area.y + rect["y2"] * scale - vy,
                REGION_RGBA_FILL, REGION_RGBA_STROKE,
            )
        # Then the live rubber band (darker / fully opaque so the user
        # can tell which one is the one they're currently editing).
        if self._region_rubber_band is not None:
            rx1, ry1, rw, rh = self._region_rubber_band
            rx2 = rx1 + rw
            ry2 = ry1 + rh
            # The rubber band's rect is in page-point space; we need
            # the same page-area adjustment the persistent overlays use.
            page_index = self.model.get_page()
            page_area = Gdk.Rectangle()
            if self.view.get_page_extents(page_index, page_area, Gtk.Border()):
                draw_rect(
                    page_area.x + rx1 * scale - vx,
                    page_area.y + ry1 * scale - vy,
                    page_area.x + rx2 * scale - vx,
                    page_area.y + ry2 * scale - vy,
                    RUBBERBAND_FILL, RUBBERBAND_STROKE, line_w=2.0,
                )
        return False
